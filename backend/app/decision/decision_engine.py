from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any

from app.copilot.intent_router import RoutingDecision
from app.decision.confidence_engine import DecisionConfidence, DecisionConfidenceEngine
from app.digital_twin.comparison_engine import FinancialComparison
from app.digital_twin.twin_engine import FinancialSnapshot


class RecommendationType(str, Enum):
    REDUCE_EXPOSURE = "reduce_exposure"
    CANCEL_SUBSCRIPTION = "cancel_subscription"
    CLOSE_EMI_EARLY = "close_emi_early"
    CLOSE_BNPL_EARLY = "close_bnpl_early"
    INCREASE_SAVINGS = "increase_savings"
    MAINTAIN_CURRENT_PLAN = "maintain_current_plan"
    DELAY_PURCHASE = "delay_purchase"
    PROCEED_WITH_PURCHASE = "proceed_with_purchase"


@dataclass
class RecommendationReason:
    """
    Structured justification for a decision recommendation.
    """

    primary_reason: str
    supporting_factors: list[str] = field(default_factory=list)
    risk_factors: list[str] = field(default_factory=list)


@dataclass
class DecisionContext:
    """
    Context passed to DecisionEngine containing financial state, simulation outputs, and metadata.
    """

    financial_snapshot: FinancialSnapshot
    comparison_result: FinancialComparison | None = None
    intent_route: RoutingDecision | None = None
    ml_predictions: dict[str, Any] = field(default_factory=dict)
    explainable_ai: dict[str, Any] = field(default_factory=dict)
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class Recommendation:
    """
    Structured recommendation generated by DecisionEngine.
    """

    recommendation_type: RecommendationType
    title: str
    action_summary: str
    reason: RecommendationReason
    expected_financial_impact: dict[str, Any] = field(default_factory=dict)
    suggested_next_action: str = ""
    confidence: DecisionConfidence | None = None


@dataclass
class DecisionResult:
    """
    Final decision output containing recommendation and execution metadata.
    """

    decision_id: str
    created_at: str
    recommendation: Recommendation
    context_summary: dict[str, Any] = field(default_factory=dict)
    metadata: dict[str, Any] = field(default_factory=dict)


class DecisionEngine:
    """
    Decision Intelligence Engine.

    Acts as the central orchestration layer for FinSight Phase 10.
    Combines outputs from Business Rules, ML Predictions, Digital Twin, and Explainable AI
    to generate ONE structured, deterministic financial recommendation. Does NOT recalculate
    business rules directly.
    """

    def __init__(
        self,
        confidence_engine: DecisionConfidenceEngine | None = None,
    ) -> None:
        self._confidence_engine = confidence_engine or DecisionConfidenceEngine()

    def evaluate_decision(self, context: DecisionContext) -> DecisionResult:
        """
        Evaluates DecisionContext and produces a single structured DecisionResult.
        """
        snap = context.financial_snapshot
        comp = context.comparison_result
        route = context.intent_route

        # Determine Recommendation Type & Rationale based on input context
        rec_type = RecommendationType.MAINTAIN_CURRENT_PLAN
        title = "Maintain Current Financial Plan"
        action_summary = "Your financial metrics are stable. Continue following your current financial plan."
        primary_reason = "Current exposure score and monthly commitments are within healthy limits."
        supporting_factors: list[str] = [f"Exposure score is {snap.exposure_score:.1f}%", f"Health score is {snap.financial_health_score:.1f}/100"]
        risk_factors: list[str] = []
        expected_impact: dict[str, Any] = {"exposure_change": 0.0, "savings_change": 0.0}
        suggested_next_action = "Review your financial dashboard monthly."

        if comp and comp.metrics:
            exp_metric = comp.metrics.get("exposure")
            savings_metric = comp.metrics.get("savings")
            commit_metric = comp.metrics.get("monthly_commitments")

            exp_diff = exp_metric.difference if exp_metric else 0.0
            savings_diff = savings_metric.difference if savings_metric else 0.0
            commit_diff = commit_metric.difference if commit_metric else 0.0

            expected_impact = {
                "exposure_change": exp_diff,
                "savings_change": savings_diff,
                "commitments_change": commit_diff,
            }

            if comp.scenario_type == "cancel_subscription":
                rec_type = RecommendationType.CANCEL_SUBSCRIPTION
                title = "Cancel Unused Subscription"
                action_summary = f"Cancel subscription to reduce monthly commitments by {abs(commit_diff):.2f}."
                primary_reason = "Cancelling recurring subscription lowers fixed monthly obligations."
                supporting_factors.append(f"Exposure score decreases by {abs(exp_diff):.2f}%")
                suggested_next_action = "Proceed to cancel subscription in your account."

            elif comp.scenario_type in ("close_emi", "close_bnpl"):
                rec_type = RecommendationType.CLOSE_EMI_EARLY if comp.scenario_type == "close_emi" else RecommendationType.CLOSE_BNPL_EARLY
                title = "Close Obligation Early"
                action_summary = f"Pre-close loan obligation to free up {abs(commit_diff):.2f} in monthly cash flow."
                primary_reason = "Early closure significantly improves available capacity and flexibility."
                supporting_factors.append(f"Monthly savings increases by {savings_diff:.2f}")
                suggested_next_action = "Initiate early loan repayment with provider."

            elif comp.scenario_type in ("add_subscription", "new_emi", "add_bnpl"):
                if snap.exposure_score > 50.0:
                    rec_type = RecommendationType.DELAY_PURCHASE
                    title = "Delay New Financial Commitment"
                    action_summary = "Delay adding new recurring commitment until existing commitments decrease."
                    primary_reason = f"Current exposure ({snap.exposure_score:.1f}%) is already moderate to high."
                    risk_factors.append(f"Adding commitment increases exposure by {exp_diff:.2f}%")
                    suggested_next_action = "Re-evaluate purchase after 3 months or after closing an existing EMI."
                else:
                    rec_type = RecommendationType.PROCEED_WITH_PURCHASE
                    title = "Proceed With Planned Purchase"
                    action_summary = "Proceed with purchase as your financial profile supports the additional commitment."
                    primary_reason = "Exposure and financial health scores remain within comfortable thresholds."
                    suggested_next_action = "Ensure monthly Autopay is set up."

            elif comp.scenario_type in ("salary_increase", "salary_reduction"):
                if comp.scenario_type == "salary_increase":
                    rec_type = RecommendationType.INCREASE_SAVINGS
                    title = "Allocate Income Increase to Savings"
                    action_summary = "Direct income increase toward emergency savings or debt reduction."
                    primary_reason = "Higher income provides opportunity to build emergency buffer."
                    suggested_next_action = "Set up automated recurring savings transfer."
                else:
                    rec_type = RecommendationType.REDUCE_EXPOSURE
                    title = "Reduce Monthly Fixed Exposure"
                    action_summary = "Review and reduce non-essential commitments following salary reduction."
                    primary_reason = "Lower income increases commitment burden ratio."
                    suggested_next_action = "Review subscriptions and discretionary spending."

        elif snap.exposure_score > 60.0:
            rec_type = RecommendationType.REDUCE_EXPOSURE
            title = "Reduce Financial Exposure"
            action_summary = "Prioritize closing active BNPL obligations or high-cost subscriptions."
            primary_reason = f"Financial exposure score is high ({snap.exposure_score:.1f}%)."
            risk_factors.append("High commitment ratio limits financial flexibility.")
            suggested_next_action = "Identify and cancel lowest-utility recurring subscriptions."

        # Calculate Decision Confidence using DecisionConfidenceEngine
        exp_delta = expected_impact.get("exposure_change", 0.0)
        commit_delta = expected_impact.get("commitments_change", 0.0)
        has_sim = comp is not None

        confidence = self._confidence_engine.calculate_confidence(
            recommendation_type=rec_type.value,
            financial_health_score=snap.financial_health_score,
            exposure_score=snap.exposure_score,
            exposure_delta=exp_delta,
            commitments_delta=commit_delta,
            simulation_applied=has_sim,
            metadata=context.metadata,
        )

        reason_obj = RecommendationReason(
            primary_reason=primary_reason,
            supporting_factors=supporting_factors,
            risk_factors=risk_factors,
        )

        recommendation = Recommendation(
            recommendation_type=rec_type,
            title=title,
            action_summary=action_summary,
            reason=reason_obj,
            expected_financial_impact=expected_impact,
            suggested_next_action=suggested_next_action,
            confidence=confidence,
        )

        decision_id = str(uuid.uuid4())
        created_at = datetime.now(timezone.utc).isoformat()

        return DecisionResult(
            decision_id=decision_id,
            created_at=created_at,
            recommendation=recommendation,
            context_summary={
                "user_id": snap.user_id,
                "exposure_score": snap.exposure_score,
                "financial_health_score": snap.financial_health_score,
                "intent": route.intent.value if route else "unknown",
                "target_engine": route.target_engine if route else "none",
                "simulation_compared": has_sim,
            },
            metadata=dict(context.metadata),
        )

    def make_decision(self, context: DecisionContext) -> DecisionResult:
        """Convenience alias for evaluate_decision."""
        return self.evaluate_decision(context)
